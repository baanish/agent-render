#!/usr/bin/env node
/**
 * Emits `public/artifact-frame.css`: the design kit as a self-contained stylesheet.
 *
 * The isolation frame (public/artifact-frame.html) is a separate document, so it cannot reuse the
 * app's bundled CSS — that bundle is hashed, Tailwind-processed, and full of app chrome. The kit
 * rules are plain CSS referencing custom properties, so the frame only needs those properties plus
 * kit.css. Generated rather than hand-maintained so the frame can never drift from the kit the
 * sanitized inline path uses.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const GLOBALS = fileURLToPath(new URL("../src/app/globals.css", import.meta.url));
const KIT = fileURLToPath(new URL("../src/app/kit.css", import.meta.url));
const OUT = fileURLToPath(new URL("../public/artifact-frame.css", import.meta.url));

/** Pulls the `:root` and `.dark`/media custom-property blocks the kit's var() references resolve against. */
function customPropertyBlocks(css) {
  const blocks = [];
  const blockPattern = /(:root|\.dark|@media\s*\(prefers-color-scheme:\s*dark\)\s*\{\s*:root)\s*\{/g;
  let match;
  while ((match = blockPattern.exec(css)) !== null) {
    let depth = 1;
    let index = blockPattern.lastIndex;
    while (index < css.length && depth > 0) {
      if (css[index] === "{") depth += 1;
      else if (css[index] === "}") depth -= 1;
      index += 1;
    }
    blocks.push(css.slice(match.index, index));
  }
  return blocks;
}

const globals = readFileSync(GLOBALS, "utf8");
const kit = readFileSync(KIT, "utf8");
const blocks = customPropertyBlocks(globals);

if (blocks.length === 0) {
  console.error("No :root custom-property block found in globals.css; the frame stylesheet would be unstyled.");
  process.exit(1);
}

const header = `/* GENERATED by scripts/build-artifact-frame-css.mjs -- edit src/app/kit.css instead. */\n`;
const body = `${header}\n${blocks.join("\n\n")}\n\n${kit}`;

const existing = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return null;
  }
})();

if (process.argv.includes("--check")) {
  if (existing !== body) {
    console.error("public/artifact-frame.css is stale. Run `npm run build:artifact-frame-css`.");
    process.exit(1);
  }
  console.log("Artifact frame stylesheet is current.");
  process.exit(0);
}

writeFileSync(OUT, body);
console.log(`Wrote ${OUT} (${blocks.length} custom-property block(s) + kit.css).`);
